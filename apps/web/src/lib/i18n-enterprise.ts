export function fillCopy(template: string, vars: Record<string, string | number>) {
  return template.replace(/\{(\w+)\}/g, (_, key: string) => String(vars[key] ?? ""));
}

export function enterpriseJobStatusLabel(status: string, locale: Locale) {
  const open = status === "open" || status === "Đang tuyển";
  if (locale === "en") return open ? "Open" : "Paused";
  return open ? "Đang tuyển" : "Tạm dừng";
}

