export function enterpriseSignalLabel(score: number | undefined, locale: Locale) {
  if (typeof score === "number") {
    return locale === "en"
      ? `Score ${score}/100 from this application's AI interview.`
      : `Điểm ${score}/100 từ buổi phỏng vấn AI của hồ sơ này.`;
  }
  return locale === "en"
    ? "No AI interview score yet; this application is not ranked."
    : "Chưa có điểm từ buổi phỏng vấn AI; hồ sơ chưa được xếp hạng.";
}

export function enterpriseDateLabel(value: string | undefined, locale: Locale) {
  if (!value || value === "—") return "—";
  const parsed = new Date(value);
  if (Number.isNaN(parsed.getTime())) return value;
  return parsed.toLocaleString(locale === "en" ? "en-GB" : "vi-VN", {
    day: "2-digit",
    month: "2-digit",
    year: "numeric",
    hour: "2-digit",
    minute: "2-digit",
  });
}

export function enterpriseDurationLabel(value: string | undefined, locale: Locale) {
  if (!value) return "";
  const seconds = Number(value);
  if (!Number.isFinite(seconds) || seconds <= 0) return value;
  const minutes = Math.floor(seconds / 60);
  const remain = seconds % 60;
  return locale === "en"
    ? `${minutes} min ${String(remain).padStart(2, "0")} sec`
    : `${minutes} phút ${String(remain).padStart(2, "0")} giây`;
}

export function enterprisePayLabel(value: string | undefined, locale: Locale) {
  if (value && value.trim()) return value;
  return locale === "en" ? "To be discussed" : "Thỏa thuận";
}

